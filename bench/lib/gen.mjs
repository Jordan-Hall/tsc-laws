const serverSource = `// A task board in one file: serves the page and keeps each room's tasks, so tests that use different rooms never meet.
import { createServer } from 'node:http';

const port = Number(process.argv[2]);
const rooms = new Map();
let nextId = 1;

const page = \`<!doctype html>
<html lang="en">
  <head><meta charset="utf-8" /><title>Task board</title></head>
  <body>
    <main>
      <h1>Task board</h1>
      <form id="add">
        <input id="title" aria-label="New task" autocomplete="off" />
        <button type="submit">Add</button>
      </form>
      <ul id="list" aria-label="Tasks"></ul>
      <p id="left" class="left" aria-live="polite"></p>
    </main>
    <script>
      const room = new URLSearchParams(location.search).get('room') || 'default';
      const list = document.getElementById('list');
      const left = document.getElementById('left');
      async function api(path, method, body) {
        const response = await fetch(path + '?room=' + encodeURIComponent(room), { method, headers: { 'content-type': 'application/json' }, body: body && JSON.stringify(body) });
        return response.json();
      }
      function render(tasks) {
        list.replaceChildren(...tasks.map((task) => {
          const li = document.createElement('li');
          li.className = task.done ? 'done' : '';
          const box = document.createElement('input');
          box.type = 'checkbox';
          box.checked = task.done;
          box.setAttribute('aria-label', 'Done: ' + task.title);
          box.addEventListener('change', async () => render(await api('/api/tasks/' + task.id + '/toggle', 'POST')));
          const title = document.createElement('span');
          title.className = 'title';
          title.textContent = task.title;
          const remove = document.createElement('button');
          remove.textContent = 'Delete';
          remove.setAttribute('aria-label', 'Delete ' + task.title);
          remove.addEventListener('click', async () => render(await api('/api/tasks/' + task.id, 'DELETE')));
          li.append(box, title, remove);
          return li;
        }));
        left.textContent = tasks.filter((task) => !task.done).length + ' left';
      }
      document.getElementById('add').addEventListener('submit', async (event) => {
        event.preventDefault();
        const field = document.getElementById('title');
        const title = field.value.trim();
        if (title === '') return;
        field.value = '';
        render(await api('/api/tasks', 'POST', { title }));
      });
      api('/api/tasks', 'GET').then(render);
    </script>
  </body>
</html>
\`;

createServer((request, response) => {
  const url = new URL(request.url ?? '/', 'http://localhost');
  const room = url.searchParams.get('room') ?? 'default';
  const json = (body) => {
    response.writeHead(200, { 'content-type': 'application/json' });
    response.end(JSON.stringify(body));
  };
  if (url.pathname === '/') {
    response.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
    return response.end(page);
  }
  const tasks = rooms.get(room) ?? [];
  if (url.pathname === '/api/tasks' && request.method === 'GET') return json(tasks);
  if (url.pathname === '/api/tasks' && request.method === 'POST') {
    let text = '';
    request.on('data', (chunk) => (text += chunk));
    request.on('end', () => {
      rooms.set(room, [...tasks, { id: nextId++, title: String(JSON.parse(text).title), done: false }]);
      json(rooms.get(room));
    });
    return;
  }
  const match = /^\\/api\\/tasks\\/(\\d+)(\\/toggle)?$/.exec(url.pathname);
  if (match !== null) {
    const id = Number(match[1]);
    const updated = match[2] === undefined ? tasks.filter((task) => task.id !== id) : tasks.map((task) => (task.id === id ? { ...task, done: !task.done } : task));
    rooms.set(room, updated);
    return json(updated);
  }
  response.writeHead(404, { 'content-type': 'text/plain' });
  response.end('not found');
}).listen(port, '127.0.0.1');
`;

export const e2ePorts = { tslaws: 47110, playwright: 47111 };

function generateE2e(size) {
  const { e2eRuns } = params;
  const groups = chunks(size);

  {
    const dir = projectDir('e2e', size, 'tslaws');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-e2e-${size}-tslaws`));
    write(join(dir, 'server.mjs'), serverSource);
    groups.forEach((ids, k) => {
      const laws = ids.map(
        (i) => `law('click-through ${i}: add, tick, reload, delete', async (n: number) => {
  const room = 'tslaws-${i}-' + n + '-' + Math.random().toString(36).slice(2);
  await open('/?room=' + room);
  await page().getByLabel('New task').fill('task ${i}');
  await page().getByRole('button', { name: 'Add' }).click();
  await page().getByRole('listitem').waitFor();
  let ok = (await page().getByRole('listitem').count()) === 1 && (await page().locator('.left').textContent()) === '1 left';
  await page().getByRole('checkbox').check();
  await page().getByText('0 left').waitFor();
  await page().reload();
  await page().getByRole('listitem').waitFor();
  ok = ok && (await page().getByRole('checkbox').isChecked()) && (await page().locator('.left').textContent()) === '0 left';
  await page().getByRole('button', { name: 'Delete' }).click();
  await page().getByRole('listitem').waitFor({ state: 'detached' });
  return ok && (await page().getByRole('listitem').count()) === 0;
});`,
      );
      write(
        join(dir, 'src', `board_${k}.e2e.laws.ts`),
        `import { law } from 'tslaws';\nimport { open, page } from 'tslaws/e2e';\n\n${laws.join('\n\n')}\n`,
      );
    });
    write(join(dir, 'tsconfig.json'), tsconfig + '\n');
    write(
      join(dir, 'tslaws.json'),
      JSON.stringify(
        {
          cover: ['src/**/*.ts', '!src/**/*.d.ts'],
          e2e: {
            server: {
              command: `node server.mjs ${e2ePorts.tslaws}`,
              url: `http://127.0.0.1:${e2ePorts.tslaws}/`,
              timeoutMs: 30000,
            },
            runs: e2eRuns,
            timeoutMs: 600000,
          },
        },
        null,
        2,
      ) + '\n',
    );
  }

  {
    const dir = projectDir('e2e', size, 'playwright');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-e2e-${size}-playwright`));
    write(join(dir, 'server.mjs'), serverSource);
    groups.forEach((ids, k) => {
      const tests = ids.map(
        (i) => `test('click-through ${i}: add, tick, reload, delete', async ({ browser }) => {
  for (let run = 0; run < ${e2eRuns}; run += 1) {
    const context = await browser.newContext({ baseURL });
    const page = await context.newPage();
    await page.goto('/?room=pw-${i}-' + run + '-' + Math.random().toString(36).slice(2));
    await page.getByLabel('New task').fill('task ${i}');
    await page.getByRole('button', { name: 'Add' }).click();
    await expect(page.getByRole('listitem')).toHaveCount(1);
    await expect(page.locator('.left')).toHaveText('1 left');
    await page.getByRole('checkbox').check();
    await expect(page.locator('.left')).toHaveText('0 left');
    await page.reload();
    await expect(page.getByRole('checkbox')).toBeChecked();
    await expect(page.locator('.left')).toHaveText('0 left');
    await page.getByRole('button', { name: 'Delete' }).click();
    await expect(page.getByRole('listitem')).toHaveCount(0);
    await context.close();
  }
});`,
      );
      write(
        join(dir, 'tests', `board_${k}.spec.ts`),
        `import { expect, test } from '@playwright/test';\n\nconst baseURL = 'http://127.0.0.1:${e2ePorts.playwright}';\n\n${tests.join('\n\n')}\n`,
      );
    });
    write(join(dir, 'tsconfig.json'), tsconfig.replace('"include": ["src"]', '"include": ["tests"]') + '\n');
    write(
      join(dir, 'playwright.config.ts'),
      `import { defineConfig } from '@playwright/test';

// BENCH_CHROME is the one Chrome every browser tool in the bench launches.
const executablePath = process.env.BENCH_CHROME;

export default defineConfig({
  testDir: 'tests',
  fullyParallel: true,
  reporter: [['json', { outputFile: 'report.json' }]],
  webServer: {
    command: 'node server.mjs ${e2ePorts.playwright}',
    url: 'http://127.0.0.1:${e2ePorts.playwright}/',
    reuseExistingServer: false,
    timeout: 30000,
  },
  use: { headless: true, launchOptions: executablePath ? { executablePath } : {} },
});
`,
    );
  }
}

/** Writes one workload at one size. */
export function generate(workload, size) {
  if (workload === 'unit-prop' || workload === 'unit-example') generateUnit(workload, size);
  else if (workload === 'browser') generateBrowser(size);
  else if (workload === 'e2e') generateE2e(size);
  else throw new Error(`unknown workload ${workload}`);
}

export const workloadNames = ['unit-prop', 'unit-example', 'browser', 'e2e'];

/** The file each tool's warm rerun changes: a marker line at the end of an imported source file. */
export function touchTarget(workload, tool, size) {
  const dir = projectDir(workload, size, tool);
  if (workload.startsWith('unit')) return join(dir, 'src', 'ops_0.ts');
  if (workload === 'browser')
    return tool === 'playwright' ? join(dir, 'widget.global.js') : join(dir, 'src', 'widget.ts');
  return join(dir, 'server.mjs');
}

/** Rewrites (or appends) the marker line in `file`, so the content differs from every earlier run. */
export function touch(file, counter) {
  const text = readFileSync(file, 'utf8');
  const marker = /\n?\/\/ bench-touch: \d+\n?$/;
  const line = `// bench-touch: ${counter}\n`;
  writeFileSync(file, marker.test(text) ? text.replace(marker, '\n' + line) : text.replace(/\n?$/, '\n') + line);
}

