// Generates the bench workloads: bench/workloads/<workload>-<size>/<tool>/. Everything under workloads/ is generated and
// ignored by git; this file and the templates in it are the source of truth.
//
// Equivalence rules, so the tools do the same work:
//   unit-prop     N property tests, each over the same generators, `runs` generated inputs each (tslaws law with
//                 --no-prove, Vitest and Rstest tests running fast-check with numRuns = runs).
//   unit-example  N example tests with one assertion each (tslaws law run once, Vitest and Rstest plain tests).
//   browser       N component checks in a real Chromium, `browserRuns` DOM walk-throughs each.
//   e2e           N click-throughs against a local server, `e2eRuns` per test, each in a fresh browser context.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = dirname(fileURLToPath(import.meta.url));
export const benchRoot = join(here, '..');
export const workloadsRoot = join(benchRoot, 'workloads');

/** Tests per file, so that a 1000-test workload is 20 files and the parallel runners have something to spread. */
export const perFile = 50;

export const params = {
  /** Generated inputs per property test (and per tslaws law). */
  runs: 100,
  /** DOM walk-throughs per browser test. */
  browserRuns: 5,
  /** Fresh-context click-throughs per e2e test. */
  e2eRuns: 2,
};

const write = (file, text) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};

const range = (n) => Array.from({ length: n }, (_, i) => i);
const chunks = (n) =>
  range(Math.ceil(n / perFile)).map((k) => range(Math.min(perFile, n - k * perFile)).map((j) => k * perFile + j));

/** Where a generated tool project lives. */
export function projectDir(workload, size, tool) {
  return join(workloadsRoot, `${workload}-${size}`, tool);
}

const tsconfig = JSON.stringify(
  {
    compilerOptions: {
      target: 'es2022',
      module: 'esnext',
      moduleResolution: 'bundler',
      lib: ['dom', 'dom.iterable', 'es2022'],
      strict: true,
      noEmit: true,
      skipLibCheck: true,
      types: [],
    },
    include: ['src'],
  },
  null,
  2,
);

const packageJson = (name) => JSON.stringify({ name, private: true, type: 'module' }, null, 2) + '\n';

// The generators tslaws derives from `number`, `string` and `number[]` (packages/tslaws/src/generators.ts), written out
// for fast-check so the competitors run the same input distribution.
const gensSource = `import * as fc from 'fast-check';

export const numbers = fc.oneof(
  { weight: 4, arbitrary: fc.integer({ min: -8, max: 8 }) },
  { weight: 3, arbitrary: fc.integer({ min: -1000, max: 1000 }) },
  { weight: 1, arbitrary: fc.integer() },
  { weight: 2, arbitrary: fc.double({ noNaN: true, noDefaultInfinity: true }) },
);
export const strings = fc.string({ maxLength: 24 });
export const numberArrays = fc.array(numbers, { maxLength: 8 });
`;

