// unit workloads

const opSources = [
  (i) => `export const add_${i} = (a: number, b: number): number => a + b + ${i};
`,
  (
    i,
  ) => `export const clamp_${i} = (x: number, lo: number, hi: number): number => Math.min(Math.max(x, lo), hi + 0 * ${i});
`,
  (i) => `export const abs_${i} = (a: number): number => Math.abs(a) + ${i};
`,
  (i) => `export function sort_${i}(xs: number[]): number[] {
  return [...xs].sort((p, q) => p - q + 0 * ${i});
}
`,
  (i) => `export const rev_${i} = (s: string): string => [...s].reverse().join('');
`,
];
const opNames = ['add', 'clamp', 'abs', 'sort', 'rev'];

/** One function per test, of the template the test index picks. */
function opsSource(ids) {
  return ['// generated by bench/lib/gen.mjs', ...ids.map((i) => opSources[i % 5](i)), '// bench-touch: 0', ''].join(
    '\n',
  );
}

// One property per template: [name, law parameters, body expression using `fn` and K]
const propertyTemplates = [
  (i) => ({
    name: `add_${i} commutes`,
    params: 'a: number, b: number',
    args: ['numbers', 'numbers'],
    names: 'a, b',
    body: `add_${i}(a, b) === add_${i}(b, a)`,
  }),
  (i) => ({
    name: `clamp_${i} stays within its bounds`,
    params: 'x: number, a: number, b: number',
    args: ['numbers', 'numbers', 'numbers'],
    names: 'x, a, b',
    body: `(() => { const lo = Math.min(a, b); const hi = Math.max(a, b); const y = clamp_${i}(x, lo, hi); return y >= lo && y <= hi; })()`,
  }),
  (i) => ({
    name: `abs_${i} is at least ${i}`,
    params: 'a: number',
    args: ['numbers'],
    names: 'a',
    body: `abs_${i}(a) >= ${i}`,
  }),
  (i) => ({
    name: `sort_${i} keeps the length and orders`,
    params: 'xs: number[]',
    args: ['numberArrays'],
    names: 'xs',
    body: `(() => { const ys = sort_${i}(xs); if (ys.length !== xs.length) return false; for (let j = 1; j < ys.length; j += 1) if (ys[j - 1]! > ys[j]!) return false; return true; })()`,
  }),
  (i) => ({
    name: `rev_${i} is its own inverse`,
    params: 's: string',
    args: ['strings'],
    names: 's',
    body: `rev_${i}(rev_${i}(s)) === s`,
  }),
];

const exampleTemplates = [
  (i) => ({
    name: `add_${i} adds`,
    body: `add_${i}(2, 3) === ${5 + i}`,
    expect: `expect(add_${i}(2, 3)).toBe(${5 + i});`,
  }),
  (i) => ({
    name: `clamp_${i} clamps`,
    body: `clamp_${i}(5, 0, 3) === 3`,
    expect: `expect(clamp_${i}(5, 0, 3)).toBe(3);`,
  }),
  (i) => ({
    name: `abs_${i} adds the offset`,
    body: `abs_${i}(-4) === ${4 + i}`,
    expect: `expect(abs_${i}(-4)).toBe(${4 + i});`,
  }),
  (i) => ({
    name: `sort_${i} sorts`,
    body: `sort_${i}([3, 1, 2]).join() === '1,2,3'`,
    expect: `expect(sort_${i}([3, 1, 2])).toEqual([1, 2, 3]);`,
  }),
  (i) => ({
    name: `rev_${i} reverses`,
    body: `rev_${i}('abc') === 'cba'`,
    expect: `expect(rev_${i}('abc')).toBe('cba');`,
  }),
];

function importsFor(ids, from) {
  const names = ids.map((i) => `${opNames[i % 5]}_${i}`);
  return `import { ${names.join(', ')} } from '${from}';`;
}

function generateUnit(workload, size) {
  const property = workload === 'unit-prop';
  const { runs } = params;
  const groups = chunks(size);
  for (const tool of ['tslaws', 'vitest', 'rstest']) {
    const dir = projectDir(workload, size, tool);
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-${workload}-${size}-${tool}`));
    groups.forEach((ids, k) => {
      write(join(dir, 'src', `ops_${k}.ts`), opsSource(ids));
      if (tool === 'tslaws') {
        const lines = ids.map((i) => {
          if (property) {
            const t = propertyTemplates[i % 5](i);
            return `law(${JSON.stringify(t.name)}, (${t.params}) => ${t.body});`;
          }
          const t = exampleTemplates[i % 5](i);
          // A law with no parameter is rejected by this tslaws build (see the zero-param probe); a run count of 1 over an
          // ignored parameter is the closest to one plain assertion.
          return `law(${JSON.stringify(t.name)}, (_run: number) => ${t.body});`;
        });
        write(
          join(dir, 'src', `ops_${k}.laws.ts`),
          `import { law } from 'tslaws';\n${importsFor(ids, `./ops_${k}`)}\n\n${lines.join('\n')}\n`,
        );
      } else {
        const lib = tool === 'vitest' ? 'vitest' : '@rstest/core';
        const head = property
          ? `import * as fc from 'fast-check';\nimport { test } from '${lib}';\nimport { numbers, numberArrays, strings } from './gens';\n`
          : `import { expect, test } from '${lib}';\n`;
        const body = ids.map((i) => {
          if (property) {
            const t = propertyTemplates[i % 5](i);
            return `test(${JSON.stringify(t.name)}, () => {\n  fc.assert(fc.property(${t.args.join(', ')}, (${t.names}) => ${t.body}), { numRuns: ${runs} });\n});`;
          }
          const t = exampleTemplates[i % 5](i);
          return `test(${JSON.stringify(t.name)}, () => {\n  ${t.expect}\n});`;
        });
        write(
          join(dir, 'src', `ops_${k}.test.ts`),
          `${head}${importsFor(ids, `./ops_${k}`)}\n\n${body.join('\n\n')}\n`,
        );
      }
    });
    if (tool === 'tslaws') {
      write(join(dir, 'tsconfig.json'), tsconfig + '\n');
      write(join(dir, 'tslaws.json'), JSON.stringify({ cover: ['src/**/*.ts', '!src/**/*.d.ts'] }, null, 2) + '\n');
    } else {
      if (property) write(join(dir, 'src', 'gens.ts'), gensSource);
      write(join(dir, 'tsconfig.json'), tsconfig + '\n');
      if (tool === 'vitest')
        write(
          join(dir, 'vitest.config.ts'),
          `import { defineConfig } from 'vitest/config';\n\nexport default defineConfig({ test: { include: ['src/**/*.test.ts'] } });\n`,
        );
      else
        write(
          join(dir, 'rstest.config.ts'),
          `import { defineConfig } from '@rstest/core';\n\nexport default defineConfig({ include: ['src/**/*.test.ts'] });\n`,
        );
    }
  }
  // The probe for zero-parameter laws: the example workload as it would be written if laws with no parameter ran.
  if (!property) {
    const dir = projectDir(workload, size, 'tslaws-zero-param');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-${workload}-${size}-tslaws-zero-param`));
    groups.forEach((ids, k) => {
      write(join(dir, 'src', `ops_${k}.ts`), opsSource(ids));
      const lines = ids.map((i) => {
        const t = exampleTemplates[i % 5](i);
        return `law(${JSON.stringify(t.name)}, () => ${t.body});`;
      });
      write(
        join(dir, 'src', `ops_${k}.laws.ts`),
        `import { law } from 'tslaws';\n${importsFor(ids, `./ops_${k}`)}\n\n${lines.join('\n')}\n`,
      );
    });
    write(join(dir, 'tsconfig.json'), tsconfig + '\n');
    write(join(dir, 'tslaws.json'), JSON.stringify({ cover: ['src/**/*.ts', '!src/**/*.d.ts'] }, null, 2) + '\n');
  }
}

