const widgetSource = `// A small task list rendered into a host element: the component every browser tool checks.
interface Task {
  id: number;
  title: string;
  done: boolean;
}

export function mountTaskList(host: HTMLElement): void {
  host.innerHTML =
    '<form class="add"><input aria-label="New task" /><button type="submit">Add</button></form>' +
    '<ul aria-label="Tasks"></ul><p class="left" aria-live="polite">0 left</p>';
  const form = host.querySelector('form')!;
  const input = host.querySelector('input')!;
  const list = host.querySelector('ul')!;
  const left = host.querySelector('.left')!;
  let tasks: Task[] = [];
  let next = 1;

  function render(): void {
    list.replaceChildren(
      ...tasks.map((task) => {
        const li = document.createElement('li');
        li.dataset.id = String(task.id);
        li.className = task.done ? 'done' : '';
        const box = document.createElement('input');
        box.type = 'checkbox';
        box.checked = task.done;
        box.setAttribute('aria-label', 'Done: ' + task.title);
        const title = document.createElement('span');
        title.className = 'title';
        title.textContent = task.title;
        const remove = document.createElement('button');
        remove.type = 'button';
        remove.className = 'delete';
        remove.textContent = 'Delete';
        remove.setAttribute('aria-label', 'Delete ' + task.title);
        li.append(box, title, remove);
        return li;
      }),
    );
    left.textContent = tasks.filter((task) => !task.done).length + ' left';
  }

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    const title = input.value.trim();
    if (title === '') return;
    tasks = [...tasks, { id: next++, title, done: false }];
    input.value = '';
    render();
  });
  list.addEventListener('click', (event) => {
    const target = event.target as HTMLElement;
    const li = target.closest('li');
    if (li === null) return;
    const id = Number(li.dataset.id);
    if (target.matches('input[type=checkbox]'))
      tasks = tasks.map((task) => (task.id === id ? { ...task, done: (target as HTMLInputElement).checked } : task));
    else if (target.matches('button.delete')) tasks = tasks.filter((task) => task.id !== id);
    else return;
    render();
  });
}
`;

/** The same component as a classic script, for the Playwright page. */
function widgetGlobal() {
  const js = ts.transpileModule(widgetSource, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  }).outputText;
  return (
    js.replace('export function mountTaskList', 'function mountTaskList') + '\nwindow.mountTaskList = mountTaskList;\n'
  );
}

/** Tasks added in one walk-through, from the generated number. */
const taskCount = (expr) => `(Math.abs(Math.trunc(${expr})) % 6) + 1`;

function browserCheckBody(i) {
  // Shared by the in-page tools: adds `count` tasks, ticks the first, deletes the last; five assertions.
  return `    const count = ${taskCount('n')};
    mountTaskList(host);
    const input = host.querySelector('input')!;
    const form = host.querySelector('form')!;
    const list = host.querySelector('ul')!;
    const left = host.querySelector('.left')!;
    for (let j = 0; j < count; j += 1) {
      input.value = 'task-${i}-' + j;
      form.requestSubmit();
    }
    let ok = list.children.length === count && left.textContent === count + ' left';
    (list.querySelector('input[type=checkbox]') as HTMLInputElement).click();
    ok = ok && left.textContent === count - 1 + ' left' && list.children[0]!.classList.contains('done');
    (list.lastElementChild!.querySelector('button.delete') as HTMLButtonElement).click();
    ok = ok && list.children.length === count - 1;
    return ok;`;
}

function generateBrowser(size) {
  const { browserRuns } = params;
  const groups = chunks(size);

  // tslaws: browser laws
  {
    const dir = projectDir('browser', size, 'tslaws');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-browser-${size}-tslaws`));
    write(join(dir, 'src', 'widget.ts'), widgetSource);
    groups.forEach((ids, k) => {
      const laws = ids.map(
        (i) => `law('task list ${i}: add, tick, delete', async (n: number) => {
  const host = mount();
  {
${browserCheckBody(i)
  .split('\n')
  .map((l) => '  ' + l)
  .join('\n')}
  }
});`,
      );
      write(
        join(dir, 'src', `list_${k}.browser.laws.ts`),
        `import { law } from 'tslaws';\nimport { mount } from 'tslaws/browser';\nimport { mountTaskList } from './widget';\n\n${laws.join('\n\n')}\n`,
      );
    });
    write(join(dir, 'tsconfig.json'), tsconfig + '\n');
    write(join(dir, 'tslaws.json'), JSON.stringify({ cover: ['src/**/*.ts', '!src/**/*.d.ts'] }, null, 2) + '\n');
  }

  // Vitest browser mode
  {
    const dir = projectDir('browser', size, 'vitest-browser');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-browser-${size}-vitest-browser`));
    write(join(dir, 'src', 'widget.ts'), widgetSource);
    write(join(dir, 'src', 'gens.ts'), gensSource);
    groups.forEach((ids, k) => {
      const tests = ids.map(
        (i) => `test('task list ${i}: add, tick, delete', () => {
  fc.assert(
    fc.property(numbers, (n) => {
      const host = document.createElement('div');
      document.body.append(host);
      try {
${browserCheckBody(i)
  .split('\n')
  .map((l) => '    ' + l)
  .join('\n')}
      } finally {
        host.remove();
      }
    }),
    { numRuns: ${browserRuns} },
  );
});`,
      );
      write(
        join(dir, 'src', `list_${k}.browser.test.ts`),
        `import * as fc from 'fast-check';\nimport { test } from 'vitest';\nimport { numbers } from './gens';\nimport { mountTaskList } from './widget';\n\n${tests.join('\n\n')}\n`,
      );
    });
    write(join(dir, 'tsconfig.json'), tsconfig + '\n');
    write(
      join(dir, 'vitest.config.ts'),
      `import { playwright } from '@vitest/browser-playwright';
import { defineConfig } from 'vitest/config';

// BENCH_CHROME is the one Chrome every browser tool in the bench launches.
const executablePath = process.env.BENCH_CHROME;

export default defineConfig({
  test: {
    include: ['src/**/*.browser.test.ts'],
    browser: {
      enabled: true,
      headless: true,
      provider: playwright({ launchOptions: executablePath ? { executablePath } : {} }),
      instances: [{ browser: 'chromium' }],
    },
  },
});
`,
    );
  }

  // Playwright Test, driving the component with locators
  {
    const dir = projectDir('browser', size, 'playwright');
    rmSync(dir, { recursive: true, force: true });
    write(join(dir, 'package.json'), packageJson(`bench-browser-${size}-playwright`));
    write(join(dir, 'widget.global.js'), widgetGlobal());
    groups.forEach((ids, k) => {
      const tests = ids.map(
        (i) => `test('task list ${i}: add, tick, delete', async ({ page }) => {
  await page.setContent('<div id="host"></div>');
  await page.addScriptTag({ path: widgetScript });
  for (const n of samples) {
    const count = ${taskCount('n')};
    await page.evaluate(() => {
      const host = document.getElementById('host')!;
      (window as any).mountTaskList(host);
    });
    for (let j = 0; j < count; j += 1) {
      await page.getByLabel('New task').fill('task-${i}-' + j);
      await page.getByRole('button', { name: 'Add' }).click();
    }
    await expect(page.getByRole('listitem')).toHaveCount(count);
    await expect(page.locator('.left')).toHaveText(count + ' left');
    await page.getByRole('checkbox').first().check();
    await expect(page.locator('.left')).toHaveText(count - 1 + ' left');
    await expect(page.getByRole('listitem').first()).toHaveClass('done');
    await page.getByRole('button', { name: 'Delete' }).last().click();
    await expect(page.getByRole('listitem')).toHaveCount(count - 1);
  }
});`,
      );
      write(
        join(dir, 'tests', `list_${k}.spec.ts`),
        `import * as fc from 'fast-check';
import { expect, test } from '@playwright/test';
import { join } from 'node:path';
import { numbers } from '../gens';

const widgetScript = join(process.cwd(), 'widget.global.js');
const samples = fc.sample(numbers, { numRuns: ${browserRuns}, seed: ${1000 + k} });

${tests.join('\n\n')}
`,
      );
    });
    write(join(dir, 'gens.ts'), gensSource);
    write(join(dir, 'tsconfig.json'), tsconfig.replace('"include": ["src"]', '"include": ["tests", "gens.ts"]') + '\n');
    write(
      join(dir, 'playwright.config.ts'),
      `import { defineConfig } from '@playwright/test';

// BENCH_CHROME is the one Chrome every browser tool in the bench launches.
const executablePath = process.env.BENCH_CHROME;

export default defineConfig({
  testDir: 'tests',
  fullyParallel: true,
  reporter: [['json', { outputFile: 'report.json' }]],
  use: { headless: true, launchOptions: executablePath ? { executablePath } : {} },
});
`,
    );
  }
}

