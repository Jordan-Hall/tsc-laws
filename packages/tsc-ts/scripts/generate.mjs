// Generates SyntaxKind, the Unicode identifier tables and the diagnostic messages
// used by src/compiler from the pinned typescript-go sources.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const upstream = resolve(root, '../../upstream/typescript-go/internal');
const out = join(root, 'src/compiler');
const header = '// Generated by scripts/generate.mjs. Do not edit.\n\n';

function syntaxKind() {
  const source = readFileSync(join(upstream, 'ast/kind_generated.go'), 'utf8');
  const block = source.slice(source.indexOf('const ('), source.indexOf('\n)\n'));
  const lines = [];
  let value = 0;
  for (const line of block.split('\n')) {
    const alias = /^\tKind(\w+)\s*=\s*Kind(\w+)$/.exec(line);
    if (alias) {
      lines.push(`  ${alias[1]} = ${alias[2]},`);
      continue;
    }
    const member = /^\tKind(\w+)(?: Kind = iota)?\s*(?:\/\/.*)?$/.exec(line);
    if (member) lines.push(`  ${member[1]} = ${value++},`);
  }
  return `${header}/** Syntax kinds, numbered like TypeScript 7. */\nexport const enum SyntaxKind {\n${lines.join('\n')}\n}\n`;
}

// Flattens a Go unicode.RangeTable into sorted, merged [first, last] pairs.
function rangeTable(source, name) {
  const start = source.indexOf(`var ${name} =`);
  const body = source.slice(start, source.indexOf('\n}\n', start));
  const ranges = [];
  for (const [, lo, hi, stride] of body.matchAll(/\{(0x[0-9A-F]+), (0x[0-9A-F]+), (\d+)\}/g)) {
    const first = Number(lo);
    const last = Number(hi);
    const step = Number(stride);
    if (step === 1) ranges.push([first, last]);
    else for (let c = first; c <= last; c += step) ranges.push([c, c]);
  }
  ranges.sort((a, b) => a[0] - b[0]);
  const merged = [];
  for (const range of ranges) {
    const previous = merged[merged.length - 1];
    if (previous !== undefined && range[0] <= previous[1] + 1) previous[1] = Math.max(previous[1], range[1]);
    else merged.push([...range]);
  }
  const pairs = merged.map(([a, b]) => `0x${a.toString(16)}, 0x${b.toString(16)}`);
  const rows = [];
  for (let i = 0; i < pairs.length; i += 4) rows.push('  ' + pairs.slice(i, i + 4).join(', ') + ',');
  return rows.join('\n');
}

function unicodeIdentifiers() {
  const source = readFileSync(join(upstream, 'stringutil/identifier_parts_generated.go'), 'utf8');
  const version = /Unicode [\d.]+/.exec(source)[0];
  return `${header}// ID_Start and ID_Continue (plus Other_ID_*) from ${version}, as [first, last] pairs.

export const identifierStartRanges: Int32Array = new Int32Array([
${rangeTable(source, 'unicodeESNextIdentifierStart')}
]);

export const identifierPartRanges: Int32Array = new Int32Array([
${rangeTable(source, 'unicodeESNextIdentifierPart')}
]);
`;
}

const categories = {
  CategoryWarning: 'Warning',
  CategoryError: 'Error',
  CategorySuggestion: 'Suggestion',
  CategoryMessage: 'Message',
};

// Emits every message referenced as `Diagnostics.Name` under src/.
function diagnosticMessages() {
  const used = new Set();
  const visit = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.name.endsWith('.ts'))
        for (const [, name] of readFileSync(path, 'utf8').matchAll(/\bDiagnostics\.(\w+)/g)) used.add(name);
    }
  };
  visit(join(root, 'src'));
  const source = readFileSync(join(upstream, 'diagnostics/diagnostics_generated.go'), 'utf8');
  const messages = new Map();
  for (const [, name, fields] of source.matchAll(/^var (\w+) = &Message\{(.*)\}$/gm)) messages.set(name, fields);
  const lines = [];
  for (const name of [...used].sort()) {
    const fields = messages.get(name);
    if (fields === undefined) throw new Error(`unknown diagnostic message ${name}`);
    const code = /code: (\d+)/.exec(fields)[1];
    const category = categories[/category: (\w+)/.exec(fields)[1]];
    const key = /key: ("(?:[^"\\]|\\.)*")/.exec(fields)[1];
    const text = /text: ("(?:[^"\\]|\\.)*")/.exec(fields)[1];
    const options = ['reportsUnnecessary', 'elidedInCompatibilityPyramid', 'reportsDeprecated'].map((option) =>
      fields.includes(`${option}: true`),
    );
    while (options.length > 0 && !options[options.length - 1]) options.pop();
    const extra = options.map((option) => `, ${option}`).join('');
    lines.push(
      `export const ${name}: DiagnosticMessage = new DiagnosticMessage(${code}, DiagnosticCategory.${category}, ${key}, ${text}${extra});`,
    );
  }
  return `${header}import { DiagnosticCategory, DiagnosticMessage } from './diagnostics.js';\n\n${lines.join('\n')}\n`;
}

const files = {
  'syntax-kind.ts': syntaxKind(),
  'unicode-identifiers.ts': unicodeIdentifiers(),
  'diagnostic-messages.ts': diagnosticMessages(),
};
for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
execFileSync(
  resolve(root, '../../node_modules/.bin/oxfmt'),
  Object.keys(files).map((name) => join(out, name)),
  {
    stdio: 'inherit',
  },
);
