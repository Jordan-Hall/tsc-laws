package main

import (
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// stdRef records a standard-library object referenced by translated code.
type stdRef struct {
	obj  types.Object
	recv *types.Named // for methods on named non-struct types
}

func (t *translator) noteStd(name string, ref stdRef) {
	if t.stdRefs == nil {
		t.stdRefs = map[string]stdRef{}
	}
	if _, ok := t.stdRefs[name]; !ok {
		t.stdRefs[name] = ref
	}
}

var exportRE = regexp.MustCompile(`(?m)^export (?:abstract )?(?:function|class|const|let) ([A-Za-z0-9_$]+)`)

func handwrittenExports(path string) map[string]bool {
	data, err := os.ReadFile(path)
	if err != nil {
		fatal(err)
	}
	out := map[string]bool{}
	for _, m := range exportRE.FindAllStringSubmatch(string(data), -1) {
		out[m[1]] = true
	}
	return out
}

// emitRuntime writes runtime.ts: the hand-written modules plus throwing
// stubs for every other referenced standard-library symbol.
func (t *translator) emitRuntime(goDir string) {
	base := handwrittenExports(filepath.Join(goDir, "base.ts"))
	std := handwrittenExports(filepath.Join(goDir, "std.ts"))
	f := &file{t: t, p: t.order[0], imports: map[string]bool{}, lits: map[*types.TypeName]map[string][]int{}}
	var w strings.Builder
	w.WriteString("// Generated by tools/gots. Do not edit.\n")
	w.WriteString("import * as $b from './base.js';\n")
	w.WriteString("import * as $s from './std.js';\n")
	w.WriteString("export * from './base.js';\n")
	w.WriteString("export * from './std.js';\n")
	resolve := regexp.MustCompile(`\$rt\.([A-Za-z0-9_$]+)`)
	fix := func(s string) string {
		return resolve.ReplaceAllStringFunc(s, func(m string) string {
			name := m[len("$rt."):]
			switch {
			case base[name]:
				return "$b." + name
			case std[name]:
				return "$s." + name
			}
			return name
		})
	}
	// Stubs can reference further std types; iterate to a fixed point.
	done := map[string]bool{}
	for {
		var names []string
		for name := range t.stdRefs {
			if !done[name] && !base[name] && !std[name] {
				names = append(names, name)
			}
		}
		if len(names) == 0 {
			break
		}
		rank := func(name string) int {
			switch o := t.stdRefs[name].obj.(type) {
			case *types.TypeName:
				if _, ok := o.Type().Underlying().(*types.Interface); ok {
					return 0
				}
				return 1
			case *types.Var:
				return 3
			}
			return 2
		}
		sort.Slice(names, func(i, j int) bool {
			if a, b := rank(names[i]), rank(names[j]); a != b {
				return a < b
			}
			return names[i] < names[j]
		})
		for _, name := range names {
			done[name] = true
			w.WriteString(fix(f.stdStub(name, t.stdRefs[name])))
		}
	}
	if err := os.WriteFile(filepath.Join(goDir, "runtime.ts"), []byte(w.String()), 0o644); err != nil {
		fatal(err)
	}
}

func (f *file) stdStub(name string, ref stdRef) string {
	what := name
	if ref.obj != nil && ref.obj.Pkg() != nil {
		what = ref.obj.Pkg().Path() + "." + ref.obj.Name()
	}
	if ref.recv != nil {
		fn := ref.obj.(*types.Func)
		sig := fn.Type().(*types.Signature)
		params, _ := f.sigParams(sig)
		return fmt.Sprintf("export function %s(recv: %s%s): %s { throw $rt.unsupported(%q); }\n", name, f.tsType(ref.recv), prefixComma(params), f.results(sig), what)
	}
	switch o := ref.obj.(type) {
	case *types.Func:
		sig := o.Type().(*types.Signature)
		params, _ := f.sigParams(sig)
		if sig.Results().Len() == 0 {
			return fmt.Sprintf("export function %s%s(%s): void { $rt.stubCall(%q, undefined); }\n", name, f.tparamList(sig.TypeParams()), params, what)
		}
		var zero string
		if sig.Results().Len() == 1 {
			zero = f.zero(sig.Results().At(0).Type())
		} else {
			var zs []string
			for i := 0; i < sig.Results().Len(); i++ {
				zs = append(zs, f.zero(sig.Results().At(i).Type()))
			}
			zero = "[" + strings.Join(zs, ", ") + "]"
		}
		return fmt.Sprintf("export function %s%s(%s): %s { return $rt.stubCall<%s>(%q, %s); }\n", name, f.tparamList(sig.TypeParams()), params, f.results(sig), f.results(sig), what, zero)
	case *types.Var:
		return fmt.Sprintf("export let %s: %s = %s;\n", name, f.tsType(o.Type()), f.zero(o.Type()))
	case *types.TypeName:
		n, ok := o.Type().(*types.Named)
		if !ok {
			return ""
		}
		if it, isIface := n.Underlying().(*types.Interface); isIface {
			var b strings.Builder
			fmt.Fprintf(&b, "export class %s extends $rt.GoObject {\n", name)
			for i := 0; i < it.NumMethods(); i++ {
				m := it.Method(i)
				if !m.Exported() {
					continue
				}
				sig := m.Type().(*types.Signature)
				ps, _ := f.sigParams(sig)
				override := ""
				if m.Name() == "Error" || m.Name() == "String" {
					override = "override "
				}
				fmt.Fprintf(&b, "  %s%s(%s): %s { throw $rt.unsupported(%q); }\n", override, m.Name(), ps, f.results(sig), what+"."+m.Name())
			}
			b.WriteString("}\n")
			return b.String()
		}
		st, isStruct := n.Underlying().(*types.Struct)
		if !isStruct {
			return ""
		}
		var b strings.Builder
		ext := "$rt.GoObject"
		// Extend the stub of a referenced library interface this type
		// implements, so values convert to it.
		var ifaceNames []string
		for other, ref := range f.t.stdRefs {
			if otn, ok := ref.obj.(*types.TypeName); ok && ref.recv == nil {
				if it, ok := otn.Type().Underlying().(*types.Interface); ok && it.NumMethods() > 0 && types.Implements(types.NewPointer(n), it) {
					ifaceNames = append(ifaceNames, other)
				}
			}
		}
		sort.Strings(ifaceNames)
		if len(ifaceNames) > 0 {
			ext = ifaceNames[0]
		}
		fmt.Fprintf(&b, "export class %s%s extends %s {\n", name, f.tparamList(n.TypeParams()), ext)
		var params, sets []string
		for i := 0; i < st.NumFields(); i++ {
			fl := st.Field(i)
			fname := fl.Name()
			if fname == "_" || !fl.Exported() {
				continue
			}
			typ := f.tsType(fl.Type())
			fmt.Fprintf(&b, "  %s: %s;\n", fname, typ)
			params = append(params, fmt.Sprintf("p%d: %s = %s", i, typ, f.zero(fl.Type())))
			sets = append(sets, fmt.Sprintf("this.%s = p%d;", fname, i))
		}
		fmt.Fprintf(&b, "  constructor(%s) { super(); %s }\n", strings.Join(params, ", "), strings.Join(sets, " "))
		for _, recvPtr := range []bool{false, true} {
			var ms *types.MethodSet
			if recvPtr {
				ms = types.NewMethodSet(types.NewPointer(n))
			} else {
				ms = types.NewMethodSet(n)
			}
			for i := 0; i < ms.Len(); i++ {
				m := ms.At(i).Obj().(*types.Func)
				if !m.Exported() || len(ms.At(i).Index()) > 1 {
					continue
				}
				if recvPtr && types.NewMethodSet(n).Lookup(m.Pkg(), m.Name()) != nil {
					continue
				}
				sig := m.Type().(*types.Signature)
				ps, _ := f.sigParams(sig)
				override := ""
				if m.Name() == "Error" || m.Name() == "String" {
					override = "override "
				}
				fmt.Fprintf(&b, "  %s%s(%s): %s { throw $rt.unsupported(%q); }\n", override, m.Name(), ps, f.results(sig), what+"."+m.Name())
			}
		}
		fmt.Fprintf(&b, "  $clone(): %s%s { return this; }\n}\n", name, typeArgNames(o))
		return b.String()
	}
	return ""
}
